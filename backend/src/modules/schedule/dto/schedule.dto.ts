import { IsString, IsEnum, IsOptional, IsNumber, IsBoolean, IsDateString, IsArray, IsIn, Min, Max } from 'class-validator';
import { ScheduleVersionType, WeekType } from '../entities/schedule-version.entity';
import { WorkloadWeekType } from '../entities/workload.entity';

// ==================== Schedule Version DTOs ====================

export class CreateScheduleVersionDto {
    @IsString()
    name: string;

    @IsEnum(ScheduleVersionType)
    @IsOptional()
    type?: ScheduleVersionType = ScheduleVersionType.TEMPLATE;

    @IsEnum(WeekType)
    @IsOptional()
    weekType?: WeekType = WeekType.SINGLE;

    @IsNumber()
    @IsOptional()
    copyFromVersionId?: number;

    @IsDateString()
    @IsOptional()
    startDate?: string;

    @IsDateString()
    @IsOptional()
    endDate?: string;

    @IsNumber()
    @IsOptional()
    @Min(1)
    @Max(127) // битовая маска: 31=Пн-Пт, 63=Пн-Сб, 127=Пн-Вс
    workingDays?: number = 31; // Пн-Пт по умолчанию

    @IsNumber()
    @IsOptional()
    @Min(1)
    @Max(10)
    maxLessonsPerDay?: number = 7;

    @IsString()
    @IsOptional()
    institutionType?: string = 'school';
}

export class UpdateScheduleVersionDto {
    @IsString()
    @IsOptional()
    name?: string;

    @IsDateString()
    @IsOptional()
    startDate?: string;

    @IsDateString()
    @IsOptional()
    endDate?: string;

    @IsNumber()
    @IsOptional()
    workingDays?: number;

    @IsNumber()
    @IsOptional()
    maxLessonsPerDay?: number;
}

export class AutoGenerateDto {
    @IsIn(['full', 'fill_gaps', 'optimize'])
    @IsOptional()
    mode?: 'full' | 'fill_gaps' | 'optimize' = 'full';

    @IsBoolean()
    @IsOptional()
    respectLocked?: boolean = true;

    @IsNumber()
    @IsOptional()
    maxIterations?: number = 10000;

    @IsNumber()
    @IsOptional()
    timeout?: number = 60; // секунды

    @IsOptional()
    priorities?: {
        minimizeWindows: number;
        teacherPreferences: number;
        roomPreferences: number;
        evenDistribution: number;
    };
}

